// ============================================================================
// Date helpers (kept private — mirror the helpers in liturgical.ts)
// ============================================================================

const MONTH_NAMES = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function toLocalDateOnly(d: Date): Date {
  return new Date(d.getFullYear(), d.getMonth(), d.getDate());
}

function addDays(d: Date, days: number): Date {
  const out = new Date(d);
  out.setDate(out.getDate() + days);
  return out;
}

function parsePaschaIso(iso: string): Date {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
}

/**
 * Compute a feast's Gregorian start date for a given calendar year.
 * Returns null if the year is outside the Pascha table for paschal feasts.
 */
function feastDateForYear(feast: Feast, year: number): Date | null {
  if (feast.type === "paschal") {
    const iso = ORTHODOX_PASCHA[year];
    if (!iso) return null;
    return addDays(parsePaschaIso(iso), feast.offset);
  }
  return new Date(year, feast.month - 1, feast.day);
}

/**
 * Format a feast for display. Single-day feasts → "Month Day". Multi-day
 * spans → "Month Day – Day" (same month) or "Month Day – Month Day"
 * (cross-month).
 */
function formatRange(start: Date, end: Date): string {
  const sm = MONTH_NAMES[start.getMonth()];
  const sd = start.getDate();
  if (start.getTime() === end.getTime()) return `${sm} ${sd}`;
  const em = MONTH_NAMES[end.getMonth()];
  const ed = end.getDate();
  if (start.getMonth() === end.getMonth()) return `${sm} ${sd} – ${ed}`;
  return `${sm} ${sd} – ${em} ${ed}`;
}

