// Public API
// ============================================================================

/**
 * Return the next `count` upcoming feasts, rendered with Gregorian dates,
 * starting from `today`. Looks at this year and next year so a December
 * "today" can still surface January feasts ahead.
 *
 * On a date today exactly equal to a feast, that feast is included
 * (today counts as upcoming).
 */
export function getUpcomingFeasts(today: Date, count: number = 4): UpcomingFeast[] {
  const start = toLocalDateOnly(today);
  const occurrences: UpcomingFeast[] = [];

  for (const feast of FEASTS) {
    for (const yearOffset of [0, 1]) {
      const year = start.getFullYear() + yearOffset;
      const date = feastDateForYear(feast, year);
      if (!date) continue;
      const duration = feast.durationDays ?? 1;
      const endDate = duration > 1 ? addDays(date, duration - 1) : date;
      // Include feasts whose end date is today or later, so an in-progress
      // multi-day feast (Bright Week mid-week, say) still surfaces.
      if (endDate.getTime() < start.getTime()) continue;
      occurrences.push({
        name: feast.name,
        note: feast.note,
        date,
        endDate,
        formatted: formatRange(date, endDate),
      });
    }
  }

  occurrences.sort((a, b) => a.date.getTime() - b.date.getTime());
  return occurrences.slice(0, count);
}
