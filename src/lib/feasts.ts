/**
 * Upcoming feasts for the homepage.
 *
 * Source of truth is liturgical: each feast is either paschal-relative
 * (a day-offset from Pascha) or fixed in the Julian calendar. We render
 * Gregorian (NS) dates so a parishioner reading the homepage on a
 * secular calendar sees the date they'll see on every wall calendar
 * around them — never the Julian Old-Style number.
 *
 * Mirrors the convention in liturgical.ts: fixed feasts are stored as
 * their NS month+day directly, since the +13 day offset is constant
 * across the 1900–2099 Pascha table window and storing NS sidesteps
 * leap-year edge cases on the Julian side.
 */

import { ORTHODOX_PASCHA } from "./pascha-dates.ts";

// ============================================================================
// Types
// ============================================================================

interface FeastBase {
  /** Display name. */
  name: string;
  /** One-line note shown beneath the date. */
  note: string;
  /**
   * If set, the feast spans this many days starting at its anchor date.
   * Used for ranges like Bright Week (`durationDays: 6`). Defaults to 1
   * (single-day display).
   */
  durationDays?: number;
}

interface PaschalFeast extends FeastBase {
  type: "paschal";
  /**
   * Days from Pascha (Pascha = 0). Negative = before, positive = after.
   * Mirrors the addDays() math in liturgical.ts.
   */
  offset: number;
}

interface FixedFeast extends FeastBase {
  type: "fixed";
  /** Gregorian (New Style) month, 1-12. */
  month: number;
  /** Gregorian (New Style) day, 1-31. */
  day: number;
}

export type Feast = PaschalFeast | FixedFeast;

export interface UpcomingFeast {
  name: string;
  note: string;
  /** Gregorian start date for this occurrence. */
  date: Date;
  /** Gregorian end date if a multi-day range; otherwise equal to `date`. */
  endDate: Date;
  /** Pre-formatted display string, e.g. "May 6" or "April 13 – 18". */
  formatted: string;
}

